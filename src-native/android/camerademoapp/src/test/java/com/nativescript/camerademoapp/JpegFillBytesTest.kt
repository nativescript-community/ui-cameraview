package com.nativescript.camerademoapp

import com.nativescript.cameraview.JpegFillBytes
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertSame
import org.junit.Test

/** Plain JVM test: runs without a device. */
class JpegFillBytesTest {
    private fun bytes(vararg v: Int) = ByteArray(v.size) { v[it].toByte() }

    // SOI, APP0 (length 4: 2 payload bytes), DQT-like segment (length 3), SOS, entropy data, EOI
    private val clean = bytes(
        0xFF, 0xD8,
        0xFF, 0xE0, 0x00, 0x04, 0x11, 0x22,
        0xFF, 0xDB, 0x00, 0x03, 0x33,
        0xFF, 0xDA, 0x00, 0x02, 0x44, 0xFF, 0x00, 0xFF, 0xFF, 0xD9
    )

    @Test
    fun aCleanJpegIsReturnedAsIs() {
        assertSame(clean, JpegFillBytes.strip(clean))
    }

    @Test
    fun fillBytesBeforeEveryHeaderMarkerAreRemoved() {
        val padded = bytes(
            0xFF, 0xD8,
            0xFF, 0xFF, 0xFF, 0xE0, 0x00, 0x04, 0x11, 0x22,
            0xFF, 0xFF, 0xDB, 0x00, 0x03, 0x33,
            0xFF, 0xFF, 0xFF, 0xFF, 0xDA, 0x00, 0x02, 0x44, 0xFF, 0x00, 0xFF, 0xFF, 0xD9
        )

        assertArrayEquals(clean, JpegFillBytes.strip(padded))
    }

    @Test
    fun entropyCodedDataIsNeverTouched() {
        // 0xFF 0xFF inside the scan is not header padding
        val padded = bytes(0xFF, 0xD8, 0xFF, 0xFF, 0xE0, 0x00, 0x03, 0x11, 0xFF, 0xDA, 0x00, 0x02, 0xFF, 0xFF, 0xFF, 0xD9)

        assertArrayEquals(
            bytes(0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x03, 0x11, 0xFF, 0xDA, 0x00, 0x02, 0xFF, 0xFF, 0xFF, 0xD9),
            JpegFillBytes.strip(padded)
        )
    }

    @Test
    fun whatIsNotAWalkableJpegIsReturnedAsIs() {
        val notJpeg = bytes(0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A)
        val truncated = bytes(0xFF, 0xD8, 0xFF, 0xFF, 0xE0, 0x00, 0x20, 0x11)

        assertSame(notJpeg, JpegFillBytes.strip(notJpeg))
        assertSame(truncated, JpegFillBytes.strip(truncated))
    }
}
